import { fold } from '../planificador/textMatch.js';

// Detectors for the brief's free text. Deliberately simple and CONSERVATIVE: a false positive only
// costs the single paid retry of generateStructured; a false negative costs trust. They always run
// on the model's own wording, i.e. with the fact tokens already removed.

// --- Rule 2: no number, price, time or percentage outside a fact token -------------------------

const NUMBER_WORDS = [
  // Spanish ("un" and "una" are articles, so they are not here)
  'uno', 'dos', 'tres', 'cuatro', 'cinco', 'seis', 'siete', 'ocho', 'nueve', 'diez', 'once', 'doce', 'trece',
  'catorce', 'quince', 'dieciseis', 'diecisiete', 'dieciocho', 'diecinueve', 'veinte', 'treinta', 'cuarenta',
  'cincuenta', 'sesenta', 'setenta', 'ochenta', 'noventa', 'cien', 'ciento', 'mil',
  // English
  'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve', 'thirteen',
  'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen', 'twenty', 'thirty', 'forty', 'fifty',
  'sixty', 'seventy', 'eighty', 'ninety', 'hundred', 'thousand',
];
const UNITS = [
  'pesos', 'dolares', 'dollars', 'euros', 'usd', 'cop', 'am', 'pm', 'a\\.m\\.', 'p\\.m\\.',
  // spans of time are figures too ("ocho anos", "ten years"); a bare "tres razones" is not
  'horas', 'hours', 'minutos', 'minutes', 'dias', 'days', 'semanas', 'weeks', 'meses', 'months', 'anos', 'years',
];

const NUMBER_PATTERNS: RegExp[] = [
  /\p{Nd}/u, // any decimal digit: 10, 3x2, 2 pm
  /[$€£]/, // currency symbols
  /%/,
  /\b(por ciento|porcentaje|percent|percentage)\b/,
  /\b(mediodia|medianoche|noon|midnight)\b/,
  // a spelled-out number followed by a unit: "cinco dolares", "dos horas", "ocho anos", "ocho pm"
  new RegExp(`\\b(${NUMBER_WORDS.join('|')})\\s+(${UNITS.join('|')})(?![\\p{L}\\p{N}])`, 'u'),
];

/** True when the text states a number, price, time or percentage (see the patterns above). */
export function mentionsNumber(text: string): boolean {
  const folded = fold(text);
  return NUMBER_PATTERNS.some((pattern) => pattern.test(folded));
}

// --- Rule 6: the AI never generates the client's product, premises or people -------------------

const GENERATION_PATTERNS: RegExp[] = [
  /\b(midjourney|dall-?e|stable diffusion|sora)\b/,
  /\b(stock photos?|stock images?|stock footage|banco de (imagenes|fotos|videos))\b/,
  /\b(ai|ia)[- ]generad[oa]s?\b|\bai[- ]generated\b/,
  /\bgenerad[oa]s?\s+(con|por|mediante|usando)\s+(ia|ai|inteligencia artificial)\b/,
  // "generate / generar ... image / foto / video" inside one sentence
  /\b(generate|generates|generating|generar|genera|generan|generen|generemos)\b[^.!?\n]{0,40}\b(image|images|imagen|imagenes|photo|photos|foto|fotos|video|videos|picture|pictures)\b/,
];

/** True when the text asks for imagery generated by AI or taken from stock (invalid in ANY field). */
export function mentionsAiGenerationRequest(text: string): boolean {
  const folded = fold(text);
  return GENERATION_PATTERNS.some((pattern) => pattern.test(folded));
}

const AI_MENTION = /\b(ia|ai|inteligencia artificial|artificial intelligence)\b/;

/**
 * True when the text mentions AI at all. Only the production fields (notas_produccion,
 * motivo_faltante, portada, musica) reject this, so a client whose business is AI can still talk
 * about it in the copy.
 */
export function mentionsAi(text: string): boolean {
  return AI_MENTION.test(fold(text));
}
